// Generates the benchmarks docs page, and the scores block in the root
// README.md, from packages/web/src/data/benchmarks.json, which
// `node packages/benchmark/src/run.mjs publish` writes after a full run.
// --check fails when either is stale.
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.join(root, "packages/web/src/data/benchmarks.json");
const target = path.join(root, "packages/web/src/content/docs/guides/benchmarks.md");
const readme = path.join(root, "README.md");
const check = process.argv.includes("--check");
const START = "<!-- benchmarks:start -->";
const END = "<!-- benchmarks:end -->";

const data = JSON.parse(fs.readFileSync(source, "utf8"));

const num = (n) => Math.round(n).toLocaleString("en-US");

function ms(n) {
  if (n == null) return "-";
  return n < 1000 ? `${Math.round(n)} ms` : `${(n / 1000).toFixed(2)} s`;
}

function bytes(n) {
  if (n == null) return "-";
  const units = ["B", "KB", "MB", "GB"];
  let i = 0;
  let v = n;
  while (v >= 1024 && i < units.length - 1) {
    v /= 1024;
    i++;
  }
  return `${v.toFixed(v >= 100 ? 0 : 1)} ${units[i]}`;
}

function table(head, align, rows) {
  const out = [`| ${head.join(" | ")} |`, `|${align.map((a) => (a === "r" ? "---:" : "---")).join("|")}|`];
  for (const r of rows) out.push(`| ${r.join(" | ")} |`);
  return out.join("\n");
}

const m = data.meta;
const date = m.date.slice(0, 10);
const byRps = (a, b) => b.rps - a.rps;

const build = table(
  ["Framework", "Version", "Median", "Best", "Output", "Client JS (gzip)"],
  ["l", "l", "r", "r", "r", "r"],
  [...data.build]
    .sort((a, b) => a.medianMs - b.medianMs)
    .map((r) => [r.id === "krate" ? `**${r.name}**` : r.name, r.version ?? "-", ms(r.medianMs), ms(r.bestMs), bytes(r.outputBytes), bytes(r.clientJsGzipBytes)]),
);

const api = table(
  ["Server", "Requests/s", "p50", "p99", "Errors"],
  ["l", "r", "r", "r", "r"],
  [...data.api].sort(byRps).map((r) => [r.name, num(r.rps), `${r.p50} ms`, `${r.p99} ms`, String(r.errors)]),
);

// Present only in a run that had scriptc installed (the target is optional).
const scriptcNote = data.api.some((r) => r.id === "krate-ts-scriptc")
  ? `- **Krate - TS API route (scriptc, experimental)** sets \`ssr.apiRuntime: "scriptc"\`: the same
  route compiled to a native executable that \`krate serve\` runs as a sidecar.
`
  : "";

const levels = data.ssrMeta?.connectionsList?.length ? data.ssrMeta.connectionsList : [...new Set(data.ssr.map((r) => r.connections))];
const ssrIds = [...new Set(data.ssr.map((r) => r.id))];
const ssr = table(
  ["Target", "Renderer", ...levels.map((l) => `${l} conn`)],
  ["l", "l", ...levels.map(() => "r")],
  ssrIds.map((id) => {
    const rows = data.ssr.filter((r) => r.id === id);
    const first = rows[0];
    const renderer = first.impl === "go" ? "Go host" : `${first.sidecar ?? "node"} SSR sidecar`;
    return [first.name, renderer, ...levels.map((l) => {
      const r = rows.find((x) => x.connections === l);
      return r ? `${num(r.rps)} req/s` : "-";
    })];
  }),
);

const toolchain = [`Node ${m.node}`, `Go ${m.go.replace(/^go/, "")}`, m.bun ? `Bun ${m.bun}` : null].filter(Boolean).join(", ");

const page = `---
title: Framework benchmarks
order: 22
description: Cold build time, client JavaScript, API route throughput and runtime-component SSR throughput for Krate against Next.js, Vite, Astro, SvelteKit and Remix.
---

# Framework benchmarks

<!-- Generated by scripts/sync-benchmarks.mjs from packages/web/src/data/benchmarks.json. Do not edit by hand. -->

Measured ${date}${m.commit ? ` at commit \`${m.commit}\`` : ""} on ${m.os} ${m.arch}, ${m.cpus} CPUs${m.model ? ` (${m.model.trim()})` : ""}; ${toolchain}.
The harness and every fixture live in
[\`packages/benchmark\`](https://github.com/kratejs/krate/tree/main/packages/benchmark).
Absolute numbers depend on the machine; read them as relative comparisons and
re-run them on your own hardware.

## Build time

A cold production build of one page: a reactive counter and a 100-item list.
Each build starts with no output directory and no build cache; the median of
${data.buildMeta?.runs ?? 3} runs is reported. Client JS is the gzip size of the
JavaScript the browser can load (for Krate \`dist\` without \`dist/.krate\`, for
Next.js \`.next/static\`, for Remix \`build/client\`).

${build}

## API route throughput

\`GET /api/json\` returning \`{"message":"hello","id":42}\`, ${data.apiMeta?.connections ?? 32}
keep-alive connections for ${Math.round((data.apiMeta?.durationMs ?? 5000) / 1000)} s after a warm-up, driven by autocannon
with ${data.apiMeta?.clientWorkers ?? 1} client worker threads so the client is not the bottleneck.

${api}

- **Krate - Go API route** is the compiled Go sidecar, load-tested directly.
- **Krate - TS API route** runs on the embedded QuickJS runtime behind
  \`krate serve\` (the default, no Node needed). Its VMs share one allocator lock,
  so it does not scale with connections.
- **Krate - TS API route (node)** sets \`ssr.apiRuntime: "node"\`: the same route
  on clustered Node workers behind \`krate serve\`.
${scriptcNote}- Node \`http\` and Go \`net/http\` are bare servers with no framework, as upper
  bounds.

## Runtime component SSR

A streaming page whose only dynamic content is one
[runtime-tier component](/docs/core-concepts/component-tiers/), served by
\`krate serve\`. TSX components render on the SSR sidecar (Node or Bun, clustered);
Go components render on the compiled Go host with no JavaScript renderer in the
path.

${ssr}

## Run it yourself

\`\`\`bash
pnpm build                                   # the SSR fixtures use the checkout's @krate/runtime
cd packages/benchmark
node src/run.mjs all                         # build + api + ssr; writes results/latest.md
node src/run.mjs publish                     # copy the run into packages/web (this page)
\`\`\`

\`--filter <id>\`, \`--runs\`, \`--duration\`, \`--connections\` and \`--client-workers\`
are described in the
[harness README](https://github.com/kratejs/krate/tree/main/packages/benchmark#options).
For desktop apps, see the [Krate Native benchmarks](/docs/native/benchmarks/).
`;

const pick = (rows, id) => rows.find((r) => r.id === id);
const kBuild = pick(data.build, "krate");
const others = data.build.filter((r) => r.id !== "krate").sort((a, b) => a.medianMs - b.medianMs);
const apiRow = (id) => pick(data.api, id);
const ssrRow = (id) => data.ssr.find((r) => r.id === id && r.connections === levels[0]);
const block = `${START}
<!-- Generated by scripts/sync-benchmarks.mjs from packages/web/src/data/benchmarks.json. -->

Measured ${date} on ${m.cpus} CPUs (${m.os}); full tables and method on the
[Framework benchmarks](https://krate.js.org/docs/guides/benchmarks/) page.

| Cold build, counter page | Median | Client JS (gzip) |
|---|---:|---:|
| **Krate** | **${ms(kBuild.medianMs)}** | **${bytes(kBuild.clientJsGzipBytes)}** |
${others.map((r) => `| ${r.name} ${r.version} | ${ms(r.medianMs)} | ${bytes(r.clientJsGzipBytes)} |`).join("\n")}

| \`GET /api/json\`, ${data.apiMeta?.connections ?? 32} connections | Requests/s |
|---|---:|
${["krate-go", "krate-ts-node", "krate-ts", "nextjs"].map(apiRow).filter(Boolean).sort(byRps).map((r) => `| ${r.name} | ${num(r.rps)} |`).join("\n")}

| Runtime component SSR, ${levels[0]} connections | Requests/s |
|---|---:|
${ssrIds.map(ssrRow).filter(Boolean).map((r) => `| ${r.name} | ${num(r.rps)} |`).join("\n")}
${END}`;

const readmeText = fs.readFileSync(readme, "utf8");
const a = readmeText.indexOf(START);
const b = readmeText.indexOf(END);
if (a < 0 || b < a) {
  console.error(`README.md has no ${START} ... ${END} block`);
  process.exit(1);
}
const readmeNext = readmeText.slice(0, a) + block + readmeText.slice(b + END.length);

const outputs = [
  [target, page],
  [readme, readmeNext],
];
let stale = false;
for (const [file, text] of outputs) {
  const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  if (current === text) continue;
  if (check) {
    console.error(`${path.relative(root, file)} is stale; run node scripts/sync-benchmarks.mjs`);
    stale = true;
  } else {
    fs.writeFileSync(file, text);
    console.log(`wrote ${path.relative(root, file)}`);
  }
}
if (stale) process.exit(1);
