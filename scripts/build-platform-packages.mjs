#!/usr/bin/env node
/**
 * Builds the per-platform binary packages (@krate/core-<platform>) that
 * @krate/core depends on, plus local dev binaries. Each package holds the
 * compiler (bin/krate) and the Krate Native shell (bin/krate-shell) side by
 * side; the compiler looks for the shell next to itself.
 *
 * These packages are intentionally NOT committed to git and live OUTSIDE the
 * pnpm workspace (in dist-platform/) so they don't affect the lockfile. They
 * are generated on demand by this script and published to npm during a release.
 *
 * Usage:
 *   node scripts/build-platform-packages.mjs
 *
 * Environment:
 *   SKIP_GO=1    Skip rebuilding the compiler (still regenerates package.json)
 *   KRATE_ONLY_PLATFORM=core-linux-x64
 *                Build one package, for checks that do not need all seven
 */

import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { platformManifest, platforms } from './platform-package.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const compilerDir = join(root, 'packages', 'compiler');
const nativeDir = join(root, 'packages', 'native');
const kratePkgDir = join(root, 'packages', 'core');
const outBase = join(root, 'dist-platform');

const version = JSON.parse(
  readFileSync(join(kratePkgDir, 'package.json'), 'utf-8'),
).version;

/**
 * Cross-compiles the Krate Native shell (packages/native/cmd/krate-shell).
 * CGO is off: the window layer loads the system webview at run time, so the
 * shell needs no C toolchain for any target. Windows builds are GUI-subsystem
 * executables (no console window); krate-shell --doctor still prints on a pipe.
 * Linux binaries are dynamically linked (purego), so the ELF interpreter is
 * the glibc loader by default and exec fails with ENOENT on Alpine. The musl
 * package names musl's loader instead; musl resolves the glibc library names
 * the binary lists by itself.
 */
const muslLoaders = { amd64: '/lib/ld-musl-x86_64.so.1', arm64: '/lib/ld-musl-aarch64.so.1' };

export function shellBuildArgs(goos, outFile, { musl = false, goarch = 'amd64' } = {}) {
  let ld = goos === 'windows' ? '-s -w -H windowsgui' : '-s -w';
  if (musl && goos === 'linux') ld += ` -I ${muslLoaders[goarch]}`;
  return ['build', '-trimpath', `-ldflags=${ld}`, '-o', outFile, './cmd/krate-shell'];
}

function buildShell(target, outDir) {
  const outFile = join(outDir, 'krate-shell' + target.ext);
  const res = spawnSync('go', shellBuildArgs(target.goos, outFile, { musl: !!target.musl, goarch: target.goarch }), {
    cwd: nativeDir,
    env: { ...process.env, GOOS: target.goos, GOARCH: target.goarch, CGO_ENABLED: '0' },
    stdio: 'inherit',
  });
  if (res.status !== 0) {
    process.exit(res.status ?? 1);
  }
}

function mib(bytes) {
  return (bytes / (1024 * 1024)).toFixed(1) + ' MiB';
}

/** Prints the size of each binary of a built package. */
function reportSizes(target) {
  const binDir = join(outBase, target.pkg, 'bin');
  let total = 0;
  for (const name of ['krate', 'krate-shell']) {
    const file = join(binDir, name + target.ext);
    if (!existsSync(file)) continue;
    const size = statSync(file).size;
    total += size;
    console.log(`    ${name + target.ext}: ${mib(size)} (${size} bytes)`);
  }
  console.log(`    ${target.pkg} binaries: ${mib(total)}`);
}

function buildCompiler(target) {
  if (process.env.SKIP_GO) return;
  const env = {
    ...process.env,
    GOOS: target.goos,
    GOARCH: target.goarch,
    CGO_ENABLED: '0',
  };
  const outDir = join(outBase, target.pkg, 'bin');
  mkdirSync(outDir, { recursive: true });
  const outFile = join(outDir, 'krate' + target.ext);
  const res = spawnSync('go', ['build', `-ldflags=-s -w -X main.version=${version}`, '-o', outFile, './cmd/krate/'], {
    cwd: compilerDir,
    env,
    stdio: 'inherit',
  });
  if (res.status !== 0) {
    process.exit(res.status ?? 1);
  }
  buildShell(target, outDir);
}

function writePackage(target) {
  const dir = join(outBase, target.pkg);
  mkdirSync(dir, { recursive: true });
  writeFileSync(
    join(dir, 'package.json'),
    JSON.stringify(platformManifest(target, version), null, 2) + '\n',
  );
  if (existsSync(join(root, 'LICENSE'))) {
    cpSync(join(root, 'LICENSE'), join(dir, 'LICENSE'));
  }
  writeFileSync(
    join(dir, 'README.md'),
    `# @krate/${target.pkg}\n\nPlatform binaries for \`@krate/core\`: \`krate\` and \`krate-shell\` (the Krate Native shell). Generated by \`scripts/build-platform-packages.mjs\` - do not edit.\n`,
  );
}

function buildLocalDevBinary() {
  if (process.env.SKIP_GO) return;
  const platform = process.platform;
  const arch = process.arch;
  let pkg = null;
  for (const t of platforms) {
    if (t.os === platform && t.cpu === arch && !t.musl) pkg = t;
  }
  if (!pkg) {
    console.log(`No matching platform package for ${platform}-${arch}; skipping local dev binary.`);
    return;
  }
  const outDir = join(kratePkgDir, 'bin');
  mkdirSync(outDir, { recursive: true });
  const outFile = join(outDir, 'krate' + pkg.ext);
  const res = spawnSync('go', ['build', `-ldflags=-s -w -X main.version=${version}`, '-o', outFile, './cmd/krate/'], {
    cwd: compilerDir,
    stdio: 'inherit',
  });
  if (res.status !== 0) process.exit(res.status ?? 1);
  buildShell(pkg, outDir);
  console.log(`Local dev binaries -> packages/core/bin/krate${pkg.ext}, krate-shell${pkg.ext}`);
}

console.log(`Generating @krate/core platform packages (version ${version})...`);
if (!process.env.SKIP_GO) {
  const sync = spawnSync('node', [join(root, 'scripts', 'sync-krate-docs.mjs')], {
    stdio: 'inherit',
  });
  if (sync.status !== 0) process.exit(sync.status ?? 1);
}
const only = process.env.KRATE_ONLY_PLATFORM;
for (const target of platforms.filter((t) => !only || t.pkg === only)) {
  const dir = join(outBase, target.pkg);
  rmSync(dir, { recursive: true, force: true });
  console.log(`  Building ${target.pkg} (${target.goos}/${target.goarch})...`);
  buildCompiler(target);
  writePackage(target);
  console.log(`    -> ${dir}`);
  reportSizes(target);
}

buildLocalDevBinary();
console.log('Done. Platform packages generated under dist-platform/ (gitignored).');
