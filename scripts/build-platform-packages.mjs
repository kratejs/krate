#!/usr/bin/env node
/**
 * Builds the per-platform binary packages (@krate/core-<platform>) that
 * @krate/core depends on, plus a local dev binary.
 *
 * These packages are intentionally NOT committed to git and live OUTSIDE the
 * pnpm workspace (in dist-platform/) so they don't affect the lockfile. They
 * are generated on demand by this script and published to npm during a release.
 *
 * Usage:
 *   node scripts/build-platform-packages.mjs
 *
 * Environment:
 *   SKIP_GO=1    Skip rebuilding the compiler (still regenerates package.json)
 */

import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const compilerDir = join(root, 'packages', 'compiler');
const kratePkgDir = join(root, 'packages', 'core');
const outBase = join(root, 'dist-platform');
const repo = {
  url: 'https://github.com/kratejs/krate.git',
  homepage: 'https://github.com/kratejs/krate',
  bugs: 'https://github.com/kratejs/krate/issues',
};

const version = JSON.parse(
  readFileSync(join(kratePkgDir, 'package.json'), 'utf-8'),
).version;

const platforms = [
  { pkg: 'core-win32-x64', os: 'win32', cpu: 'x64', goos: 'windows', goarch: 'amd64', ext: '.exe' },
  { pkg: 'core-win32-arm64', os: 'win32', cpu: 'arm64', goos: 'windows', goarch: 'arm64', ext: '.exe' },
  { pkg: 'core-linux-x64', os: 'linux', cpu: 'x64', goos: 'linux', goarch: 'amd64', ext: '' },
  { pkg: 'core-linux-x64-musl', os: 'linux', cpu: 'x64', goos: 'linux', goarch: 'amd64', ext: '', musl: true },
  { pkg: 'core-linux-arm64', os: 'linux', cpu: 'arm64', goos: 'linux', goarch: 'arm64', ext: '' },
  { pkg: 'core-darwin-x64', os: 'darwin', cpu: 'x64', goos: 'darwin', goarch: 'amd64', ext: '' },
  { pkg: 'core-darwin-arm64', os: 'darwin', cpu: 'arm64', goos: 'darwin', goarch: 'arm64', ext: '' },
];

function buildCompiler(target) {
  if (process.env.SKIP_GO) return;
  const env = {
    ...process.env,
    GOOS: target.goos,
    GOARCH: target.goarch,
    CGO_ENABLED: '0',
  };
  const outDir = join(outBase, target.pkg, 'bin');
  mkdirSync(outDir, { recursive: true });
  const outFile = join(outDir, 'krate' + target.ext);
  const res = spawnSync('go', ['build', `-ldflags=-s -w -X main.version=${version}`, '-o', outFile, './cmd/krate/'], {
    cwd: compilerDir,
    env,
    stdio: 'inherit',
  });
  if (res.status !== 0) {
    process.exit(res.status ?? 1);
  }
}

function writePackage(target) {
  const dir = join(outBase, target.pkg);
  mkdirSync(dir, { recursive: true });
  writeFileSync(
    join(dir, 'package.json'),
    JSON.stringify(
      {
        name: `@krate/${target.pkg}`,
        version,
        description: `The Krate compiler binary for ${target.os} ${target.cpu}${target.musl ? ' (musl)' : ''}.`,
        license: 'Apache-2.0',
        os: [target.os],
        cpu: [target.cpu],
        homepage: repo.homepage,
        repository: { type: 'git', url: repo.url },
        bugs: { url: repo.bugs },
        keywords: ['krate', 'ssg', 'compiler', target.os, target.cpu],
        files: ['bin'],
        bin: { krate: `bin/krate${target.ext}` },
      },
      null,
      2,
    ) + '\n',
  );
  if (existsSync(join(root, 'LICENSE'))) {
    cpSync(join(root, 'LICENSE'), join(dir, 'LICENSE'));
  }
  writeFileSync(
    join(dir, 'README.md'),
    `# @krate/${target.pkg}\n\nPlatform binary for \`@krate/core\`. Generated by \`scripts/build-platform-packages.mjs\` — do not edit.\n`,
  );
}

function buildLocalDevBinary() {
  if (process.env.SKIP_GO) return;
  const platform = process.platform;
  const arch = process.arch;
  let pkg = null;
  for (const t of platforms) {
    if (t.os === platform && t.cpu === arch && !t.musl) pkg = t;
  }
  if (!pkg) {
    console.log(`No matching platform package for ${platform}-${arch}; skipping local dev binary.`);
    return;
  }
  const outDir = join(kratePkgDir, 'bin');
  mkdirSync(outDir, { recursive: true });
  const outFile = join(outDir, 'krate' + pkg.ext);
  const res = spawnSync('go', ['build', `-ldflags=-s -w -X main.version=${version}`, '-o', outFile, './cmd/krate/'], {
    cwd: compilerDir,
    stdio: 'inherit',
  });
  if (res.status !== 0) process.exit(res.status ?? 1);
  console.log(`Local dev binary -> packages/core/bin/krate${pkg.ext}`);
}

console.log(`Generating @krate/core platform packages (version ${version})...`);
for (const target of platforms) {
  const dir = join(outBase, target.pkg);
  rmSync(dir, { recursive: true, force: true });
  console.log(`  Building ${target.pkg} (${target.goos}/${target.goarch})...`);
  buildCompiler(target);
  writePackage(target);
  console.log(`    -> ${dir}`);
}

buildLocalDevBinary();
console.log('Done. Platform packages generated under dist-platform/ (gitignored).');
