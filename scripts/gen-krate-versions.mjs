#!/usr/bin/env node
/**
 * Generates packages/compiler/internal/migrate/krateversions_gen.go, the table
 * of the version of every @krate package a release publishes. `krate migrate
 * nextjs` writes dependency ranges from it, so a package that versions on its
 * own (@krate/three, @krate/konva) never gets the runtime's range.
 *
 * Usage:
 *   node scripts/gen-krate-versions.mjs          write the file
 *   node scripts/gen-krate-versions.mjs --check  fail when it is stale
 *
 * set-version.mjs runs it after bumping the versions and check-version.mjs
 * runs the check, so the table cannot drift from the package.json files.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { releasePackages } from './release-packages.mjs';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
export const krateVersionsFile = 'packages/compiler/internal/migrate/krateversions_gen.go';

export function renderKrateVersions(rootDir = root) {
  const rows = [];
  for (const dir of releasePackages) {
    const pkg = JSON.parse(readFileSync(join(rootDir, 'packages', dir, 'package.json'), 'utf8'));
    if (!pkg.name.startsWith('@krate/')) continue;
    rows.push({ name: pkg.name, dir, version: pkg.version });
  }
  rows.sort((a, b) => a.name.localeCompare(b.name));
  const lines = rows.map((r) => `\t{Name: ${JSON.stringify(r.name)}, Dir: ${JSON.stringify(r.dir)}, Version: ${JSON.stringify(r.version)}},`);
  return [
    '// Code generated by scripts/gen-krate-versions.mjs; DO NOT EDIT.',
    '',
    'package migrate',
    '',
    '// krateReleases lists every @krate package a release publishes, with its',
    '// directory under packages/ and its version in this checkout.',
    'var krateReleases = []krateRelease{',
    ...lines,
    '}',
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const file = join(root, krateVersionsFile);
  const want = renderKrateVersions();
  if (process.argv.includes('--check')) {
    let have = '';
    try {
      have = readFileSync(file, 'utf8');
    } catch {}
    if (have !== want) {
      console.error(`${krateVersionsFile} is stale; run node scripts/gen-krate-versions.mjs`);
      process.exit(1);
    }
    console.log(`${krateVersionsFile} is up to date`);
  } else {
    writeFileSync(file, want);
    console.log(`wrote ${krateVersionsFile}`);
  }
}
