package gobind

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"
)

// BakeCall is one call of a //krate:build function: the registry id
// ("<module id>.<name>") and its literal arguments as a JSON array.
type BakeCall struct {
	ID   string
	Args string
}

// BakeResult is the outcome of one BakeCall. OK holds the wire JSON of the
// result when the call succeeded.
type BakeResult struct {
	OK   json.RawMessage `json:"ok,omitempty"`
	Code string          `json:"code,omitempty"`
	Err  string          `json:"err,omitempty"`
}

// BakeError is a failure to build or run the evaluator; Output is what the Go
// command printed.
type BakeError struct {
	Msg    string
	Output string
}

func (e *BakeError) Error() string { return e.Msg }

const bakeMain = `// Code generated by krate. DO NOT EDIT.

package main

import (
	"encoding/json"
	"fmt"
	"os"

%s
	"github.com/kratejs/krate/packages/native/krate"
	"github.com/kratejs/krate/packages/native/scheme"
	"github.com/kratejs/krate/packages/native/wire"
)

type call struct {
	ID   string          ` + "`json:\"id\"`" + `
	Args json.RawMessage ` + "`json:\"args\"`" + `
}

type outcome struct {
	OK   json.RawMessage ` + "`json:\"ok,omitempty\"`" + `
	Code string          ` + "`json:\"code,omitempty\"`" + `
	Err  string          ` + "`json:\"err,omitempty\"`" + `
}

func run(r *scheme.Registry, c call) (out outcome) {
	defer func() {
		if v := recover(); v != nil {
			out = outcome{Code: "panic", Err: fmt.Sprint("panic: ", v)}
		}
	}()
	e := wire.NewEncoder()
	e.Raw(c.Args)
	frame, err := e.Finish()
	if err != nil {
		return outcome{Code: "bad_request", Err: err.Error()}
	}
	res, err := r.Invoke(krate.Background(), c.ID, frame)
	if err != nil {
		if ke, ok := err.(*krate.Error); ok {
			return outcome{Code: ke.Code, Err: ke.Message}
		}
		return outcome{Code: "internal", Err: err.Error()}
	}
	d, err := wire.NewDecoder(res)
	if err != nil {
		return outcome{Code: "internal", Err: err.Error()}
	}
	if d.Blobs() > 0 {
		return outcome{Code: "bad_result", Err: "the result holds binary data, which cannot be baked"}
	}
	raw, err := d.RawValue()
	if err != nil {
		return outcome{Code: "internal", Err: err.Error()}
	}
	return outcome{OK: json.RawMessage(append([]byte(nil), raw...))}
}

func main() {
	r := scheme.NewRegistry()
%s
	var calls []call
	if err := json.NewDecoder(os.Stdin).Decode(&calls); err != nil {
		fmt.Fprintln(os.Stderr, "reading calls:", err)
		os.Exit(2)
	}
	out := make([]outcome, len(calls))
	for i, c := range calls {
		out[i] = run(r, c)
	}
	if err := json.NewEncoder(os.Stdout).Encode(out); err != nil {
		fmt.Fprintln(os.Stderr, "writing results:", err)
		os.Exit(2)
	}
}
`

// Evaluate runs the calls of //krate:build functions in a small generated Go
// program that links the glue of res (so the arguments and results go through
// the same wire conversion as a run-time call) and returns one result per
// call. The program is built inside the project's Go module; it needs the Go
// toolchain.
func Evaluate(root, outDir string, res *Result, calls []BakeCall) ([]BakeResult, error) {
	var imports, regs strings.Builder
	for i, g := range res.Glue {
		fmt.Fprintf(&imports, "\tglue%d %s\n", i, strconv.Quote(g.ImportPath))
		fmt.Fprintf(&regs, "\tglue%d.Register(r)\n", i)
	}
	src := fmt.Sprintf(bakeMain, imports.String(), regs.String())
	dir := filepath.Join(outDir, "bake")
	if err := writeIfChanged(filepath.Join(dir, "main.go"), []byte(src)); err != nil {
		return nil, err
	}
	rel, err := filepath.Rel(root, dir)
	if err != nil {
		return nil, err
	}
	in := make([]map[string]json.RawMessage, len(calls))
	for i, c := range calls {
		id, _ := json.Marshal(c.ID)
		in[i] = map[string]json.RawMessage{"id": id, "args": json.RawMessage(c.Args)}
	}
	input, err := json.Marshal(in)
	if err != nil {
		return nil, err
	}
	cmd := exec.Command("go", "run", "./"+filepath.ToSlash(rel))
	cmd.Dir = root
	cmd.Stdin = bytes.NewReader(input)
	var stdout, stderr bytes.Buffer
	cmd.Stdout, cmd.Stderr = &stdout, &stderr
	if err := cmd.Run(); err != nil {
		msg := strings.TrimSpace(stderr.String())
		if msg == "" {
			msg = err.Error()
		}
		if _, lookErr := exec.LookPath("go"); lookErr != nil {
			return nil, &BakeError{Msg: "the go command is not installed", Output: lookErr.Error()}
		}
		return nil, &BakeError{Msg: "go run of the build function evaluator failed", Output: msg}
	}
	var out []BakeResult
	if err := json.Unmarshal(stdout.Bytes(), &out); err != nil || len(out) != len(calls) {
		return nil, &BakeError{Msg: "the build function evaluator printed an unreadable result", Output: strings.TrimSpace(stdout.String() + stderr.String())}
	}
	return out, nil
}
