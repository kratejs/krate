package gobind

import (
	"fmt"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

const tsHeader = "// Code generated by krate. DO NOT EDIT.\n"

var tsIdentRe = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

var jsReserved = map[string]bool{
	"break": true, "case": true, "catch": true, "class": true, "const": true, "continue": true,
	"debugger": true, "default": true, "delete": true, "do": true, "else": true, "enum": true,
	"export": true, "extends": true, "false": true, "finally": true, "for": true, "function": true,
	"if": true, "import": true, "in": true, "instanceof": true, "new": true, "null": true,
	"return": true, "super": true, "switch": true, "this": true, "throw": true, "true": true,
	"try": true, "typeof": true, "var": true, "void": true, "while": true, "with": true,
	"let": true, "static": true, "yield": true, "await": true, "implements": true,
	"interface": true, "package": true, "private": true, "protected": true, "public": true,
	"arguments": true, "eval": true, "opts": true,
}

// tsParamNames returns TypeScript-safe, unique parameter names.
func tsParamNames(it *hostItem) []string {
	used := map[string]bool{"opts": true}
	out := make([]string, len(it.params))
	for i, p := range it.params {
		n := p.name
		if n == "" || n == "_" {
			n = "arg" + strconv.Itoa(i)
		}
		for jsReserved[n] || used[n] {
			n += "_"
		}
		used[n] = true
		out[i] = n
	}
	return out
}

type tsDecl struct {
	name string
	w    *wtype
}

// tsGen renders wire types as TypeScript for one module.
type tsGen struct {
	names map[string]string
	taken map[string]bool
	queue []tsDecl
}

func newTSGen() *tsGen { return &tsGen{names: map[string]string{}, taken: map[string]bool{}} }

func (t *tsGen) nameFor(w *wtype) string {
	key := typeKey(w.gt)
	if n, ok := t.names[key]; ok {
		return n
	}
	base := namedBase(w.named)
	name := base
	if t.taken[name] && w.named.Obj().Pkg() != nil {
		name = capitalize(w.named.Obj().Pkg().Name()) + "_" + base
	}
	for i := 2; t.taken[name]; i++ {
		name = base + strconv.Itoa(i)
	}
	t.taken[name] = true
	t.names[key] = name
	t.queue = append(t.queue, tsDecl{name, w})
	return name
}

func arrayOf(x string) string {
	if strings.ContainsAny(x, "|&") || strings.Contains(x, "=>") {
		x = "(" + x + ")"
	}
	return x + "[]"
}

func (t *tsGen) ref(w *wtype) string {
	if w.named != nil && w.kind != kTime {
		return t.nameFor(w)
	}
	return t.body(w)
}

func tsKey(name string) string {
	if tsIdentRe.MatchString(name) {
		return name
	}
	return strconv.Quote(name)
}

func (t *tsGen) fieldLines(w *wtype, indent string) []string {
	var out []string
	for _, f := range w.fields {
		opt := ""
		if f.omitEmpty {
			opt = "?"
		}
		out = append(out, fmt.Sprintf("%s%s%s: %s;", indent, tsKey(f.json), opt, t.ref(f.t)))
	}
	return out
}

func (t *tsGen) body(w *wtype) string {
	switch w.kind {
	case kBool:
		return "boolean"
	case kString:
		return "string"
	case kInt, kUint, kFloat:
		return "number"
	case kBytes:
		return "Uint8Array"
	case kTime:
		return "Date"
	case kSlice, kArray:
		return arrayOf(t.ref(w.elem))
	case kMap:
		return "Record<string, " + t.ref(w.elem) + ">"
	case kPtr:
		return t.ref(w.elem) + " | null"
	case kStruct:
		if len(w.fields) == 0 {
			return "{}"
		}
		var parts []string
		for _, l := range t.fieldLines(w, "") {
			parts = append(parts, strings.TrimSuffix(l, ";"))
		}
		return "{ " + strings.Join(parts, "; ") + " }"
	}
	return "unknown"
}

func (t *tsGen) declSource(d tsDecl) string {
	if d.w.kind == kStruct {
		lines := t.fieldLines(d.w, "  ")
		if len(lines) == 0 {
			return "export interface " + d.name + " {}\n"
		}
		return "export interface " + d.name + " {\n" + strings.Join(lines, "\n") + "\n}\n"
	}
	return "export type " + d.name + " = " + t.body(d.w) + ";\n"
}

// dts renders the declaration file for a module's host items.
func dts(items []*hostItem) string {
	t := newTSGen()
	sorted := append([]*hostItem(nil), items...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].name < sorted[j].name })
	var sigs strings.Builder
	useOpts, useSignal := false, false
	for _, it := range sorted {
		switch it.kind {
		case itemSignal:
			useSignal = true
			fmt.Fprintf(&sigs, "export const %s: ReadonlyHostSignal<%s>;\n", it.exportName(), t.ref(it.result))
		default:
			useOpts = useOpts || !it.build
			names := tsParamNames(it)
			var ps []string
			for i, p := range it.params {
				ps = append(ps, names[i]+": "+t.ref(p.w))
			}
			if !it.build {
				ps = append(ps, "opts?: CallOptions")
			}
			ret := "Promise<void>"
			switch {
			case it.kind == itemStream:
				ret = "AsyncIterable<" + t.ref(it.result) + ">"
			case it.build:
				ret = t.ref(it.result)
			case it.result != nil:
				ret = "Promise<" + t.ref(it.result) + ">"
			}
			fmt.Fprintf(&sigs, "export function %s(%s): %s;\n", it.exportName(), strings.Join(ps, ", "), ret)
		}
	}
	// Declarations can reference further named types, so drain by index.
	decls := map[string]string{}
	var names []string
	for i := 0; i < len(t.queue); i++ {
		d := t.queue[i]
		decls[d.name] = t.declSource(d)
		names = append(names, d.name)
	}
	sort.Strings(names)

	var b strings.Builder
	b.WriteString(tsHeader)
	var imp []string
	if useOpts {
		imp = append(imp, "CallOptions")
	}
	if useSignal {
		imp = append(imp, "ReadonlyHostSignal")
	}
	if len(imp) > 0 {
		b.WriteString("import type { " + strings.Join(imp, ", ") + " } from \"@krate/app\";\n")
	}
	b.WriteString("\n")
	for _, n := range names {
		b.WriteString(decls[n] + "\n")
	}
	b.WriteString(sigs.String())
	return b.String()
}

// stub renders the JavaScript module the UI bundle imports in place of a .go
// file. Signals are created on first use so importing the module never opens
// a connection.
func stub(items []*hostItem) string {
	sorted := append([]*hostItem(nil), items...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].name < sorted[j].name })
	var used = map[string]bool{}
	var body strings.Builder
	for _, it := range sorted {
		id := strconv.Quote(it.id)
		switch it.kind {
		case itemSignal:
			used["signal"] = true
			fmt.Fprintf(&body, "export const %s = __sig(%s);\n", it.exportName(), id)
		default:
			fn := "call"
			if it.kind == itemStream {
				fn = "stream"
			}
			if it.build {
				fn = "baked"
			}
			used[fn] = true
			var ps, as []string
			for i := range it.params {
				ps = append(ps, "a"+strconv.Itoa(i))
				as = append(as, "a"+strconv.Itoa(i))
			}
			if it.build {
				fmt.Fprintf(&body, "export const %s = (%s) => __baked(%s, [%s]);\n", it.exportName(), strings.Join(ps, ", "), id, strings.Join(as, ", "))
				continue
			}
			ps = append(ps, "opts")
			fmt.Fprintf(&body, "export const %s = (%s) => __%s(%s, [%s], opts);\n", it.exportName(), strings.Join(ps, ", "), fn, id, strings.Join(as, ", "))
		}
	}
	var b strings.Builder
	b.WriteString(tsHeader)
	var imp []string
	for _, n := range []string{"call", "stream", "signal", "baked"} {
		if used[n] {
			imp = append(imp, n+" as __"+n)
		}
	}
	b.WriteString("import { " + strings.Join(imp, ", ") + " } from \"@krate/app\";\n\n")
	if used["signal"] {
		b.WriteString("const __sig = (name) => {\n  let s;\n  const get = () => (s ??= __signal(name));\n  const f = () => get()();\n  f.subscribe = (fn) => get().subscribe(fn);\n  return f;\n};\n\n")
	}
	b.WriteString(body.String())
	return b.String()
}
