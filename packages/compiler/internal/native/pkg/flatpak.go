const (
	defaultFlatpakRuntime        = "org.gnome.Platform"
	defaultFlatpakRuntimeVersion = "48"
)

// flatpakRuntime returns the runtime id, its version and the matching SDK.
func flatpakRuntime(m Metadata) (rt, ver, sdk string) {
	rt, ver = m.Flatpak.Runtime, m.Flatpak.RuntimeVersion
	if rt == "" {
		rt = defaultFlatpakRuntime
	}
	if ver == "" {
		ver = defaultFlatpakRuntimeVersion
	}
	sdk = strings.TrimSuffix(rt, ".Platform") + ".Sdk"
	return
}

func flatpakArch(a string) string {
	if a == "arm64" {
		return "aarch64"
	}
	return "x86_64"
}

// flatpakDesktop is the launcher: the icon is named by the app id, because
// Flatpak exports only files that start with it.
func flatpakDesktop(m Metadata) []byte {
	return []byte(desktopentry.Entry(desktopentry.Options{
		Name: m.ProductName, Exec: m.slug(), Icon: m.AppID, Comment: m.summaryOf(),
		Schemes: m.DeepLinks, MimeTypes: desktopMimeTypes(m), Categories: desktopCategories(m.MacCategory), StartupWMClass: m.AppID,
	}))
}

// FlatpakManifest returns the flatpak-builder manifest (YAML). sources is the
// YAML text of the module's source entries, indented by the caller.
func FlatpakManifest(m Metadata, sources string) []byte {
	rt, ver, sdk := flatpakRuntime(m)
	slug := m.slug()
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
	w("# Generated by krate native package. Edit krate.config.ts, not this file.")
	w("app-id: %s", m.AppID)
	w("runtime: %s", rt)
	w("runtime-version: %s", yamlQuote(ver))
	w("sdk: %s", sdk)
	w("command: %s", slug)
	w("finish-args:")
	for _, a := range flatpakFinishArgs(m) {
		w("  - %s", yamlQuote(a))
	}
	w("modules:")
	w("  - name: %s", slug)
	w("    buildsystem: simple")
	w("    build-commands:")
	cmds := []string{
		fmt.Sprintf("install -d /app/lib/%s", slug),
		fmt.Sprintf("cp -a files/. /app/lib/%s/", slug),
		"install -d /app/bin",
		fmt.Sprintf("ln -s ../lib/%s/%s /app/bin/%s", slug, slug, slug),
		fmt.Sprintf("install -Dm644 %s.desktop /app/share/applications/%s.desktop", m.AppID, m.AppID),
		fmt.Sprintf("install -Dm644 %s.metainfo.xml /app/share/metainfo/%s.metainfo.xml", m.AppID, m.AppID),
		"cp -a icons/. /app/share/icons/",
	}
	if len(m.FileTypes()) > 0 {
		cmds = append(cmds, fmt.Sprintf("install -Dm644 %s.xml /app/share/mime/packages/%s.xml", m.AppID, m.AppID))
	}
	for _, c := range cmds {
		w("      - %s", yamlQuote(c))
	}
	w("    sources:")
	b.WriteString(sources)
	return []byte(b.String())
}

// flatpakFiles lays out the directory flatpak-builder takes as its source:
// files/ (the app), the launcher, metainfo, mime types and icons named by the
// app id.
func flatpakFiles(o *Options, ic *Icon, ut *tree) (*tree, error) {
	m := o.Meta
	t := newTree()
	for _, e := range ut.sorted() {
		c := *e
		c.Path = "files/" + e.Path
		t.put(&c)
	}
	t.addData(m.AppID+".desktop", 0o644, flatpakDesktop(m))
	t.addData(m.AppID+".metainfo.xml", 0o644, AppStreamMetainfo(m, m.AppID+".desktop", buildTime()))
	if x := SharedMimeXML(m); x != nil {
		t.addData(m.AppID+".xml", 0o644, x)
	}
	for _, s := range hicolorSizes {
		data, err := ic.PNG(s)
		if err != nil {
			return nil, fail(diag.CodeNativePkgIcon, "native.icons", err.Error(), "")
		}
		t.addData(fmt.Sprintf("icons/hicolor/%dx%d/apps/%s.png", s, s, m.AppID), 0o644, data)
	}
	return t, nil
}

// packageFlatpak writes the flatpak-builder inputs and, when flatpak-builder
// is installed, builds a .flatpak bundle.
func packageFlatpak(o *Options, ic *Icon, ut *tree, res *Result) error {
	m, p := o.Meta, o.Payload
	if err := validateSandboxMeta(m, "flatpak"); err != nil {
		return err
	}
	dir := filepath.Join(o.OutDir, "flatpak-"+p.Arch)
	if err := os.RemoveAll(dir); err != nil {
		return wrapWrite(dir, err)
	}
	t, err := flatpakFiles(o, ic, ut)
	if err != nil {
		return err
	}
	if err := writeDisk(dir, t); err != nil {
		return wrapWrite(dir, err)
	}
	local := filepath.Join(dir, m.AppID+".yml")
	if err := writeFileAtomic(local, FlatpakManifest(m, "      - type: dir\n        path: .\n")); err != nil {
		return wrapWrite(local, err)
	}
	res.add(Artifact{Path: local, Format: "flatpak-manifest", Detail: "flatpak-builder manifest"})

	// The Flathub manifest builds from a source archive that holds the same
	// directory, so the build needs no network beyond fetching that archive.
	srcName := fmt.Sprintf("%s-%s-flatpak-sources-%s.tar.gz", m.slug(), m.Version, p.Arch)
	srcPath := filepath.Join(o.OutDir, srcName)
	if err := writeTarGzFile(srcPath, t); err != nil {
		return wrapWrite(srcPath, err)
	}
	sum, err := fileSHA256(srcPath)
	if err != nil {
		return wrapWrite(srcPath, err)
	}
	url := srcName
	if o.UpdateBaseURL != "" {
		url = strings.TrimRight(o.UpdateBaseURL, "/") + "/" + srcName
	} else {
		res.note("flatpak: set --update-base-url to the directory that will host %s; the Flathub manifest names it by file name only", srcName)
	}
	arch := flatpakArch(p.Arch)
	src := fmt.Sprintf("      - type: archive\n        url: %s\n        sha256: %s\n        only-arches:\n          - %s\n", yamlQuote(url), sum, arch)
	flathub := filepath.Join(o.OutDir, m.AppID+".flathub.yml")
	if err := writeFileAtomic(flathub, FlatpakManifest(m, src)); err != nil {
		return wrapWrite(flathub, err)
	}
	res.add(Artifact{Path: srcPath, Format: "flatpak-sources", Detail: "source archive for the Flathub manifest"})
	res.add(Artifact{Path: flathub, Format: "flathub-manifest", Detail: "for a Flathub pull request"})

	if err := validateMetainfo(o, filepath.Join(dir, m.AppID+".metainfo.xml"), res); err != nil {
		return err
	}

	if _, err := o.Runner.LookPath("flatpak-builder"); err != nil {
		res.note("no .flatpak bundle: flatpak-builder was not found in PATH (apt install flatpak-builder; then flatpak install flathub %s//%s %s//%s); the manifest is in %s", rtID(m), rtVer(m), sdkID(m), rtVer(m), dir)
		return nil
	}
	if _, err := o.Runner.LookPath("flatpak"); err != nil {
		res.note("no .flatpak bundle: flatpak was not found in PATH (apt install flatpak)")
		return nil
	}
	if o.Runner.GOOS() != "linux" {
		res.note("no .flatpak bundle: flatpak-builder runs on Linux only")
		return nil
	}
	repo, build := filepath.Join(dir, "repo"), filepath.Join(dir, "build")
	args := []string{"--force-clean", "--disable-rofiles-fuse", "--arch=" + arch, "--repo=" + repo}
	if os.Getenv("KRATE_FLATPAK_INSTALL_DEPS") == "1" {
		args = append(args, "--user", "--install-deps-from=flathub")
	}
	args = append(args, build, local)
	if out, err := o.run(dir, nil, "flatpak-builder", args...); err != nil {
		return fail(diag.CodeNativeSandboxPkg, local, "flatpak-builder failed:\n"+indentLines(trimTail(string(out), 20)),
			fmt.Sprintf("install the runtime and SDK first: flatpak install flathub %s//%s %s//%s (or set KRATE_FLATPAK_INSTALL_DEPS=1)", rtID(m), rtVer(m), sdkID(m), rtVer(m)))
	}
	bundle := filepath.Join(o.OutDir, artifactName(m, p, ".flatpak"))
	if out, err := o.run(dir, nil, "flatpak", "build-bundle", "--arch="+arch, repo, bundle, m.AppID); err != nil {
		return fail(diag.CodeNativeSandboxPkg, bundle, "flatpak build-bundle failed:\n"+indentLines(trimTail(string(out), 20)), "")
	}
	res.add(Artifact{Path: bundle, Format: "flatpak"})
	return nil
}

func rtID(m Metadata) string  { r, _, _ := flatpakRuntime(m); return r }
func rtVer(m Metadata) string { _, v, _ := flatpakRuntime(m); return v }
func sdkID(m Metadata) string { _, _, s := flatpakRuntime(m); return s }

func fileSHA256(p string) (string, error) {
	f, err := os.Open(p)
	if err != nil {
		return "", err
	}
	defer f.Close()
	h := sha256.New()
	if _, err := io.Copy(h, f); err != nil {
		return "", err
	}
	return hex.EncodeToString(h.Sum(nil)), nil
}

// trimTail keeps the last n lines of s.
func trimTail(s string, n int) string {
	lines := strings.Split(strings.TrimSpace(s), "\n")
	if len(lines) > n {
		lines = lines[len(lines)-n:]
	}
	return strings.Join(lines, "\n")
}

// validateSandboxMeta checks what Flatpak and Snap need from the metadata.
func validateSandboxMeta(m Metadata, format string) error {
	if m.AppID == "" || strings.Count(m.AppID, ".") < 2 {
		return fail(diag.CodeNativeSandboxPkg, "native.appId", fmt.Sprintf("a %s needs an app id with at least three parts, such as com.acme.notes (got %q)", format, m.AppID),
			"Flathub and the Snap Store build their ids from the reverse-DNS app id")
	}
	return nil
}

// validateMetainfo runs appstreamcli when it is installed and fails on errors.
// appstreamcli also fails on warnings and infos (a missing homepage, a short
// first paragraph); those do not stop a local package and are reported as a
// note, because Flathub's own checks are where they matter.
func validateMetainfo(o *Options, path string, res *Result) error {
	if _, err := o.Runner.LookPath("appstreamcli"); err != nil {
		res.note("the AppStream metainfo was not validated: appstreamcli is not installed (apt install appstream)")
		return nil
	}
	out, err := o.run("", nil, "appstreamcli", "validate", "--no-net", path)
	if err == nil {
		return nil
	}
	if onlyAppStreamWarnings(string(out)) {
		res.note("appstreamcli has remarks about the AppStream metainfo (set native.bundle.linux.summary, description, license and homepage before publishing to Flathub):\n%s", indentLines(trimTail(string(out), 12)))
		return nil
	}
	return fail(diag.CodeNativeSandboxPkg, path, "appstreamcli rejected the metainfo:\n"+indentLines(trimTail(string(out), 12)),
		"set native.bundle.linux.summary, description, license and homepage; the file is kept in the flatpak directory")
}

// onlyAppStreamWarnings reports whether appstreamcli's output lists remarks
// (W: warnings, I: infos, P: pedantic) and no E: errors. Output it does not
// recognize counts as an error.
func onlyAppStreamWarnings(out string) bool {
	remarks := 0
	for _, line := range strings.Split(out, "\n") {
		line = strings.TrimSpace(line)
		switch {
		case strings.HasPrefix(line, "E:"):
			return false
		case strings.HasPrefix(line, "W:"), strings.HasPrefix(line, "I:"), strings.HasPrefix(line, "P:"):
			remarks++
		}
	}
	return remarks > 0
}
