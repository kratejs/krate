var snapNameBad = regexp.MustCompile(`[^a-z0-9-]+`)

// snapName turns the product name into a snap name: lowercase letters,
// digits and single dashes, starting with a letter, 2 to 40 characters.
func snapName(m Metadata) string {
	n := strings.Trim(snapNameBad.ReplaceAllString(strings.ToLower(m.slug()), "-"), "-")
	for strings.Contains(n, "--") {
		n = strings.ReplaceAll(n, "--", "-")
	}
	if n == "" || n[0] < 'a' || n[0] > 'z' {
		n = "app-" + n
	}
	if len(n) > 40 {
		n = strings.TrimRight(n[:40], "-")
	}
	if len(n) < 2 {
		n += "-app"
	}
	return n
}

func snapArch(a string) string {
	if a == "arm64" {
		return "arm64"
	}
	return "amd64"
}

func snapGrade(m Metadata) string {
	if m.Snap.Grade != "" {
		return m.Snap.Grade
	}
	return "stable"
}

func snapConfinement(m Metadata) string {
	if m.Snap.Confinement != "" {
		return m.Snap.Confinement
	}
	return "strict"
}

// snapLicense maps the SPDX expression to what snapcraft accepts.
func snapLicense(m Metadata) string {
	l := m.licenseOf()
	if l == "LicenseRef-proprietary" {
		return "Proprietary"
	}
	return l
}

func snapDesktop(m Metadata) []byte {
	return []byte(desktopentry.Entry(desktopentry.Options{
		Name: m.ProductName, Exec: snapName(m), Icon: "${SNAP}/meta/gui/icon.png", Comment: m.summaryOf(),
		Schemes: m.DeepLinks, MimeTypes: desktopMimeTypes(m), Categories: desktopCategories(m.MacCategory), StartupWMClass: m.AppID,
	}))
}

// SnapcraftYAML returns snapcraft.yaml: a core24 snap with the gnome extension
// (GTK 3 and the desktop integration) and WebKitGTK 4.1 staged from the
// Ubuntu archive.
func SnapcraftYAML(m Metadata, arch string) []byte {
	name, slug := snapName(m), m.slug()
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
	w("# Generated by krate native package. Edit krate.config.ts, not this file.")
	w("name: %s", name)
	w("title: %s", yamlQuote(oneLine(m.ProductName)))
	w("version: %s", yamlQuote(m.Version))
	w("summary: %s", yamlQuote(m.summaryOf()))
	w("description: |")
	for _, l := range strings.Split(m.descriptionOf(), "\n") {
		w("  %s", strings.TrimRight(l, " \t\r"))
	}
	w("license: %s", yamlQuote(snapLicense(m)))
	if m.Homepage != "" {
		w("website: %s", yamlQuote(m.Homepage))
	}
	w("base: core24")
	w("grade: %s", snapGrade(m))
	w("confinement: %s", snapConfinement(m))
	w("icon: snap/gui/icon.png")
	w("platforms:")
	w("  %s:", snapArch(arch))
	w("    build-on: [%s]", snapArch(arch))
	w("    build-for: [%s]", snapArch(arch))
	w("apps:")
	w("  %s:", name)
	w("    command: usr/lib/%s/%s", slug, slug)
	w("    extensions: [gnome]")
	w("    desktop: usr/share/applications/%s.desktop", m.AppID)
	w("    environment:")
	w("      GTK_USE_PORTAL: \"1\"")
	w("    plugs:")
	for _, p := range snapPlugs(m) {
		w("      - %s", p)
	}
	w("parts:")
	w("  app:")
	w("    plugin: dump")
	w("    source: files")
	w("    stage-packages:")
	w("      - libwebkit2gtk-4.1-0")
	return []byte(b.String())
}

// packageSnap writes the snapcraft project and, when snapcraft is installed,
// builds the .snap.
func packageSnap(o *Options, ic *Icon, ut *tree, res *Result) error {
	m, p := o.Meta, o.Payload
	if err := validateSandboxMeta(m, "snap"); err != nil {
		return err
	}
	dir := filepath.Join(o.OutDir, "snap-"+p.Arch)
	if err := os.RemoveAll(dir); err != nil {
		return wrapWrite(dir, err)
	}
	slug := m.slug()
	t := newTree()
	for _, e := range ut.sorted() {
		c := *e
		c.Path = "files/usr/lib/" + slug + "/" + e.Path
		t.put(&c)
	}
	t.addData("files/usr/share/applications/"+m.AppID+".desktop", 0o644, snapDesktop(m))
	if x := SharedMimeXML(m); x != nil {
		t.addData("files/usr/share/mime/packages/"+m.AppID+".xml", 0o644, x)
	}
	png, err := ic.PNG(512)
	if err != nil {
		return fail(diag.CodeNativePkgIcon, "native.icons", err.Error(), "")
	}
	t.addData("snap/gui/icon.png", 0o644, png)
	t.addData("snap/snapcraft.yaml", 0o644, SnapcraftYAML(m, p.Arch))
	if err := writeDisk(dir, t); err != nil {
		return wrapWrite(dir, err)
	}
	yml := filepath.Join(dir, "snap", "snapcraft.yaml")
	res.add(Artifact{Path: yml, Format: "snapcraft-yaml", Detail: "snapcraft project"})

	if _, err := o.Runner.LookPath("snapcraft"); err != nil {
		res.note("no .snap: snapcraft was not found in PATH (sudo snap install snapcraft --classic); build it with `snapcraft pack` in %s", dir)
		return nil
	}
	if o.Runner.GOOS() != "linux" {
		res.note("no .snap: snapcraft builds on Linux only")
		return nil
	}
	out := filepath.Join(o.OutDir, artifactName(m, p, ".snap"))
	args := []string{"pack", "--output", out}
	if os.Getenv("KRATE_SNAP_DESTRUCTIVE") == "1" {
		// Build on this machine instead of in an LXD container (CI runners).
		args = append(args, "--destructive-mode")
	}
	if b, err := o.run(dir, nil, "snapcraft", args...); err != nil {
		return fail(diag.CodeNativeSandboxPkg, yml, "snapcraft failed:\n"+indentLines(trimTail(string(b), 20)),
			"snapcraft builds in LXD by default: run `lxd init --auto` first, or set KRATE_SNAP_DESTRUCTIVE=1 on an Ubuntu 24.04 machine")
	}
	res.add(Artifact{Path: out, Format: "snap"})
	return nil
}
