// Package gotsgen parses Go component files and generates TypeScript declaration
// files (.d.go.ts) so `import { Card } from "./card.go"` type-checks, and
// exposes the component metadata the Go host scaffolding needs.
package gotsgen

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// Tier identifies whether a Go component renders at build time or per request.
type Tier string

const (
	TierServer  Tier = "server"
	TierRuntime Tier = "runtime"
)

// Component describes one exported Go component function.
type Component struct {
	Name       string // Go func name (also the TS export name)
	Tier       Tier
	PropsType  string // props struct type name ("" when untyped)
	Path       string // absolute source path
	dir        string
	HasResult  bool // returns (T, error)
	ResultHTML bool // return type is HTML/string (vs a scalar)
	// HasRequest is true when the function takes a second `krate.Request`
	// parameter (runtime components can read the incoming request).
	HasRequest bool
}

// ParseFile parses one Go file and returns its components. A file is a component
// file when it is named *.server.go / *.runtime.go, or when it carries a
// `//krate:component` directive. Individual funcs may also carry a directive.
func ParseFile(path string, src []byte) ([]Component, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, path, src, parser.ParseComments)
	if err != nil {
		return nil, fmt.Errorf("parsing %s: %w", path, err)
	}

	fileTier, fileIsComponent := fileTierOf(path)
	if dt := directiveTier(f.Doc); dt != "" {
		fileTier = dt
		fileIsComponent = true
	}

	var comps []Component
	for _, decl := range f.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Recv != nil || !fn.Name.IsExported() {
			continue
		}
		directive := directiveTier(fn.Doc)
		if !fileIsComponent && directive == "" {
			continue
		}
		tier := fileTier
		if directive != "" {
			tier = directive
		}
		if tier == "" {
			tier = TierServer
		}
		c := Component{Name: fn.Name.Name, Tier: tier, Path: path, dir: filepath.Dir(path)}
		// Params: an optional props struct (first) and an optional krate.Request
		// (second). Both are named types.
		if params := fn.Type.Params; params != nil {
			var types []ast.Expr
			for _, p := range params.List {
				types = append(types, p.Type)
			}
			if len(types) >= 1 {
				c.PropsType = identName(types[0])
			}
			if len(types) >= 2 {
				c.HasRequest = true
			}
		}
		// Result kind: HTML/string vs scalar, and (T, error).
		if res := fn.Type.Results; res != nil {
			if len(res.List) == 2 {
				c.HasResult = true
			}
			if len(res.List) >= 1 {
				c.ResultHTML = isHTMLish(res.List[0].Type)
			}
		}
		comps = append(comps, c)
	}
	return comps, nil
}

// Generate returns the TypeScript declaration (.d.go.ts) source for a Go
// component file.
func Generate(path string, src []byte) (string, error) {
	body, err := generateBody(path, src, nil)
	if err != nil {
		return "", err
	}
	return "// Code generated by krate. DO NOT EDIT.\n" +
		"import type {} from \"@krate/runtime\";\n\n" + body, nil
}

// GenerateAmbientModule returns an ambient wildcard module declaration for a
// component file, so imports of that `.go` file type-check from any location
// (the declarations live under .krate/types, not next to the source). dirStructs
// carries struct types declared in sibling files of the same package so
// cross-file prop types resolve instead of degrading to `unknown`.
func GenerateAmbientModule(pattern, path string, src []byte, dirStructs map[string]*ast.StructType) (string, error) {
	body, err := generateBody(path, src, dirStructs)
	if err != nil {
		return "", err
	}
	return "// Code generated by krate. DO NOT EDIT.\n" +
		"declare module \"" + pattern + "\" {\n" + body + "}\n", nil
}

// CollectStructs parses every non-underscore `.go` file in dir and returns the
// struct types they declare, so a component file can reference a props type
// defined in a sibling file of the same package.
func CollectStructs(dir string) map[string]*ast.StructType {
	out := map[string]*ast.StructType{}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return out
	}
	fset := token.NewFileSet()
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") || strings.HasPrefix(e.Name(), "_") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, e.Name()), nil, 0)
		if err != nil {
			continue
		}
		collectFileStructs(f, out)
	}
	return out
}

// collectFileStructs adds the struct type declarations in f to out.
func collectFileStructs(f *ast.File, out map[string]*ast.StructType) {
	for _, decl := range f.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE {
			continue
		}
		for _, spec := range gd.Specs {
			ts, ok := spec.(*ast.TypeSpec)
			if !ok {
				continue
			}
			if st, ok := ts.Type.(*ast.StructType); ok {
				out[ts.Name.Name] = st
			}
		}
	}
}

// generateBody renders the interfaces + component declarations for a file.
func generateBody(path string, src []byte, dirStructs map[string]*ast.StructType) (string, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, path, src, parser.ParseComments)
	if err != nil {
		return "", fmt.Errorf("parsing %s: %w", path, err)
	}
	comps, err := ParseFile(path, src)
	if err != nil {
		return "", err
	}

	// Struct type names resolvable for this file: those declared in the file
	// plus any from sibling files in the same package.
	structs := map[string]*ast.StructType{}
	for k, v := range dirStructs {
		structs[k] = v
	}
	collectFileStructs(f, structs)

	var b strings.Builder
	// Emit an interface for every struct declared in the file (stable order).
	names := make([]string, 0, len(structs))
	for name := range structs {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		b.WriteString("export interface " + name + " {\n")
		for _, field := range structs[name].Fields.List {
			if len(field.Names) == 0 {
				continue
			}
			tsType := goTypeToTS(field.Type, structs)
			jsonName, optional := jsonFieldName(field, field.Names[0].Name)
			key := jsonName
			if !isTSIdent(jsonName) {
				key = "\"" + jsonName + "\""
			}
			opt := ""
			if optional {
				opt = "?"
			}
			b.WriteString("  " + key + opt + ": " + tsType + ";\n")
		}
		b.WriteString("}\n\n")
	}

	for _, c := range comps {
		props := c.PropsType
		if props == "" {
			props = "Record<string, unknown>"
		}
		b.WriteString("export declare const " + c.Name + ": (props: " + props + ") => JSX.Element;\n")
	}
	return b.String(), nil
}

// fileTierOf derives the tier from a filename suffix.
func fileTierOf(path string) (Tier, bool) {
	base := strings.ToLower(filepath.Base(path))
	switch {
	case strings.HasSuffix(base, ".runtime.go"):
		return TierRuntime, true
	case strings.HasSuffix(base, ".server.go"):
		return TierServer, true
	}
	return "", false
}

// directiveTier scans a comment group for `krate:component [server|runtime]`.
func directiveTier(doc *ast.CommentGroup) Tier {
	if doc == nil {
		return ""
	}
	for _, c := range doc.List {
		text := strings.TrimSpace(strings.TrimPrefix(c.Text, "//"))
		text = strings.TrimSpace(strings.TrimPrefix(text, "/*"))
		if !strings.Contains(text, "krate:component") {
			continue
		}
		rest := strings.TrimSpace(strings.TrimPrefix(text, "krate:component"))
		switch {
		case strings.HasPrefix(rest, "runtime"):
			return TierRuntime
		case strings.HasPrefix(rest, "server"):
			return TierServer
		default:
			return TierServer
		}
	}
	return ""
}

// identName returns the identifier name of a type expression (unwrapping a
// pointer), or "" when it is not a simple named type.
func identName(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.StarExpr:
		return identName(t.X)
	}
	return ""
}

// isHTMLish reports whether a return type is HTML/string (vs a scalar).
func isHTMLish(e ast.Expr) bool {
	switch t := e.(type) {
	case *ast.Ident:
		return t.Name == "string"
	case *ast.SelectorExpr:
		return t.Sel.Name == "HTML" || t.Sel.Name == "Node"
	}
	return false
}

// jsonFieldName returns the JSON name and optionality for a struct field.
func jsonFieldName(field *ast.Field, goName string) (string, bool) {
	name, optional := goName, false
	if field.Tag != nil {
		tag := strings.Trim(field.Tag.Value, "`")
		if idx := strings.Index(tag, `json:"`); idx >= 0 {
			raw := tag[idx+len(`json:"`):]
			if end := strings.Index(raw, `"`); end >= 0 {
				raw = raw[:end]
			}
			parts := strings.Split(raw, ",")
			if parts[0] != "" && parts[0] != "-" {
				name = parts[0]
			}
			for _, p := range parts[1:] {
				if p == "omitempty" {
					optional = true
				}
			}
		}
	}
	if _, isPtr := field.Type.(*ast.StarExpr); isPtr {
		optional = true
	}
	return name, optional
}

// isTSIdent reports whether s is a valid TS/JS identifier (unquoted keys).
func isTSIdent(s string) bool {
	if s == "" {
		return false
	}
	for i := 0; i < len(s); i++ {
		ch := s[i]
		if i == 0 {
			if !(ch == '_' || ch == '$' || (ch >= 'A' && ch <= 'Z') || (ch >= 'a' && ch <= 'z')) {
				return false
			}
		} else if !(ch == '_' || ch == '$' || (ch >= 'A' && ch <= 'Z') || (ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) {
			return false
		}
	}
	return true
}

// goTypeToTS maps a Go type expression to a TypeScript type.
func goTypeToTS(e ast.Expr, structs map[string]*ast.StructType) string {
	switch t := e.(type) {
	case *ast.Ident:
		switch t.Name {
		case "string":
			return "string"
		case "bool":
			return "boolean"
		case "int", "int8", "int16", "int32", "int64",
			"uint", "uint8", "uint16", "uint32", "uint64",
			"float32", "float64", "byte", "rune":
			return "number"
		case "any", "error":
			return "unknown"
		}
		if _, ok := structs[t.Name]; ok {
			return t.Name
		}
		// Known HTML aliases without a selector (e.g. a local HTML type).
		if t.Name == "HTML" || t.Name == "Node" {
			return "JSX.Element"
		}
		return "unknown"
	case *ast.StarExpr:
		return goTypeToTS(t.X, structs) + " | undefined"
	case *ast.ArrayType:
		return goTypeToTS(t.Elt, structs) + "[]"
	case *ast.MapType:
		return "Record<" + goTypeToTS(t.Key, structs) + ", " + goTypeToTS(t.Value, structs) + ">"
	case *ast.SelectorExpr:
		pkg, _ := t.X.(*ast.Ident)
		if pkg != nil {
			if pkg.Name == "time" && t.Sel.Name == "Time" {
				return "string"
			}
			if t.Sel.Name == "HTML" || t.Sel.Name == "Node" {
				return "JSX.Element"
			}
		}
		return "unknown"
	case *ast.StructType, *ast.InterfaceType:
		return "unknown"
	}
	return "unknown"
}
