package regionwire

import (
	_ "embed"
	"strings"
)

//go:embed frame.go
var frameSource string

// HostSource returns the encoder as the source of a file in package pkg, for
// the generated Go host (which cannot import this internal package).
func HostSource(pkg string) string {
	_, body, _ := strings.Cut(frameSource, "\npackage regionwire\n")
	return "// Code generated by krate. DO NOT EDIT.\n\n// Frame encoder of the region wire format; see\n// packages/compiler/internal/regionwire.\npackage " + pkg + "\n" + body
}
