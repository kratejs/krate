package gohost

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/kratejs/krate/packages/compiler/internal/config"
)

// writeModule resolves and writes <modDir>/go.mod (plus go.sum when available),
// returning the module path used for import rewriting.
// Precedence:
//  1. src/api/go.mod - copied verbatim (its own module clause honored).
//  2. src/components/go.mod - same, for component packages.
//  3. project-root go.mod - module path defaults to krate-goapi, copying the
//     root's go version and require/replace/exclude, rebasing relative replaces.
//  4. generated module - krate-goapi + config deps/replaces/exclude.
func WriteModule(modDir, apiSrcDir, root string, cfg config.GoCfg) (string, error) {
	modulePath := cfg.Module
	if modulePath == "" {
		modulePath = DefaultModulePath
	}

	for _, srcDir := range []string{apiSrcDir, filepath.Join(root, filepath.FromSlash(DefaultComponentDir))} {
		data, err := os.ReadFile(filepath.Join(srcDir, "go.mod"))
		if err != nil {
			continue
		}
		if err := os.WriteFile(filepath.Join(modDir, "go.mod"), []byte(EnsureGoextRequire(string(data))), 0644); err != nil {
			return "", err
		}
		if sum, err := os.ReadFile(filepath.Join(srcDir, "go.sum")); err == nil {
			_ = os.WriteFile(filepath.Join(modDir, "go.sum"), sum, 0644)
		}
		if mp := ParseModulePath(string(data)); mp != "" {
			modulePath = mp
		}
		return modulePath, nil
	}

	var sb strings.Builder
	fmt.Fprintf(&sb, "module %s\n\n", modulePath)

	goVersion := "1.25"
	if data, err := os.ReadFile(filepath.Join(root, "go.mod")); err == nil {
		v, directives := SplitGoMod(string(data))
		if v != "" {
			goVersion = v
		}
		directives = RebaseReplacePaths(directives)
		fmt.Fprintf(&sb, "go %s\n\n", goVersion)
		if directives != "" {
			sb.WriteString(directives)
			sb.WriteString("\n")
		}
		if sum, err := os.ReadFile(filepath.Join(root, "go.sum")); err == nil {
			_ = os.WriteFile(filepath.Join(modDir, "go.sum"), sum, 0644)
		}
	} else {
		fmt.Fprintf(&sb, "go %s\n\n", goVersion)
	}

	for _, d := range cfg.Deps {
		if d.Path != "" {
			fmt.Fprintf(&sb, "require %s %s\n", d.Path, d.Version)
		}
	}
	for _, e := range cfg.Exclude {
		if e.Path != "" {
			fmt.Fprintf(&sb, "exclude %s %s\n", e.Path, e.Version)
		}
	}
	for _, r := range cfg.Replaces {
		if r.From != "" {
			fmt.Fprintf(&sb, "replace %s => %s\n", r.From, r.To)
		}
	}
	// The helper packages live under the real krate module path; replace it with
	// the locally vendored copy so builds work offline. When a project go.mod
	// already provides the module, keep that instead.
	if !strings.Contains(sb.String(), GoextModulePath) {
		fmt.Fprintf(&sb, "\nrequire %s v0.0.0\n", GoextModulePath)
		fmt.Fprintf(&sb, "replace %s => ../goext\n", GoextModulePath)
	}
	if err := os.WriteFile(filepath.Join(modDir, "go.mod"), []byte(sb.String()), 0644); err != nil {
		return "", err
	}
	return modulePath, nil
}

// writeGoWork writes a go.work at the project root (refresh-only for our own
// generated file) so gopls resolves the real goext import path for the
// project's Go sources. The vendored goext module is included only when the
// project's own go.mod does not already provide the module path.
func writeGoWork(root string) {
	workPath := filepath.Join(root, GoWorkName)
	if data, err := os.ReadFile(workPath); err == nil {
		if !strings.HasPrefix(string(data), "// Code generated by krate") {
			return // never clobber a user-authored workspace
		}
	}
	hasRoot := false
	rootRefsGoext := false
	goVer := "1.25"
	if data, err := os.ReadFile(filepath.Join(root, "go.mod")); err == nil {
		hasRoot = true
		rootRefsGoext = strings.Contains(string(data), GoextModulePath)
		if v, _ := SplitGoMod(string(data)); v != "" {
			goVer = v
		}
	}
	var b strings.Builder
	b.WriteString("// Code generated by krate. DO NOT EDIT.\n")
	b.WriteString("go " + goVer + "\n\nuse (\n")
	if hasRoot {
		b.WriteString("\t.\n")
	}
	b.WriteString("\t.krate/" + HostModuleName + "\n")
	if !rootRefsGoext {
		b.WriteString("\t.krate/" + GoextModuleName + "\n")
	}
	b.WriteString(")\n")
	_ = os.WriteFile(workPath, []byte(b.String()), 0644)
}
