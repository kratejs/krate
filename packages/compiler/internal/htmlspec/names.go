// AttrName maps a JSX prop name to the emitted attribute name. Unknown names
// (including already-correct SVG camelCase names such as viewBox and
// markerHeight) pass through unchanged.
func AttrName(name string) string {
	if mapped, ok := attrAliases[name]; ok {
		return mapped
	}
	return name
}
