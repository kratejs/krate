// ServerPlan describes a bundled portable server (build.BuildServerBundle) for
// the deploy adapters.
type ServerPlan struct {
	Target string
	// Bundle is the absolute path of the generated entry.
	Bundle string
	// Exclude lists dist-relative slash paths that must not be published as
	// static files (shells of request-time pages, dynamic templates): the
	// bundle carries them.
	Exclude []string
	// ServerPaths are URL globs that must reach the function.
	ServerPaths   []string
	HasMiddleware bool
	HasActions    bool
	HasAPI        bool
	// UsesRevalidate reports revalidatePath/revalidateTag calls in the sources.
	UsesRevalidate  bool
	ShutdownTimeout int
	Port            int
	// Warnings are filled by Emit for the caller to print.
	Warnings []string
}

// ServerTargets run the portable server handler.
var ServerTargets = []string{"node", "vercel", "netlify", "cloudflare"}

// WantsServer reports whether a deploy to target must bundle the server: the
// node target always, the platform targets when the project has server
// features (and --static-only was not given).
func WantsServer(target string, features []string, staticOnly bool) bool {
	if target == "node" {
		return true
	}
	if staticOnly || len(features) == 0 {
		return false
	}
	return target == "vercel" || target == "netlify" || target == "cloudflare"
}

const generatedMarker = "Generated by `krate deploy"

// emitServer writes the platform files for a bundled server.
func emitServer(target string, cfg *config.Config, root, outDir string, plan *ServerPlan) ([]string, error) {
	if plan == nil || plan.Bundle == "" {
		return nil, fmt.Errorf("the %s target runs this project's server features and needs the server bundle (krate deploy builds it; library callers pass Options.Server from build.BuildServerBundle)", target)
	}
	if target == "node" {
		return []string{plan.Bundle}, nil
	}
	if plan.UsesRevalidate {
		plan.Warnings = append(plan.Warnings, "revalidatePath/revalidateTag are called by this project: on "+target+" they only reach the instance that handled the request; other instances keep their cached pages until the revalidate window ends (see guides/deployment: caches on serverless)")
	}
	if plan.HasMiddleware && target != "cloudflare" {
		plan.Warnings = append(plan.Warnings, "middleware runs only for requests that reach the function: statically prerendered pages and assets are served by the "+target+" CDN first and bypass it. Make guarded pages SSR/ISR (config = { ssr: true }) so they run through the middleware")
	}
	if err := stripStatic(outDir, plan.Exclude); err != nil {
		return nil, err
	}
	// Server-only dist artifacts were removed above; the bundle was written
	// inside them, so keep a copy of what we read first.
	bundleData, err := os.ReadFile(plan.Bundle)
	if err != nil {
		return nil, fmt.Errorf("reading server bundle: %w", err)
	}
	_ = os.RemoveAll(filepath.Join(outDir, ".krate"))

	switch target {
	case "vercel":
		return emitVercelServer(cfg, root, outDir, plan, bundleData)
	case "netlify":
		return emitNetlifyServer(cfg, root, outDir, plan, bundleData)
	case "cloudflare":
		return emitCloudflareServer(cfg, root, outDir, plan, bundleData)
	}
	return nil, fmt.Errorf("unknown server target %q", target)
}

// stripStatic removes server-only artifacts and request-time page shells from
// the public output.
func stripStatic(outDir string, exclude []string) error {
	for _, legacy := range []string{"api-node", "server-manifest.json"} {
		if err := os.RemoveAll(filepath.Join(outDir, legacy)); err != nil && !os.IsNotExist(err) {
			return err
		}
	}
	for _, rel := range exclude {
		if err := os.Remove(filepath.Join(outDir, filepath.FromSlash(rel))); err != nil && !os.IsNotExist(err) {
			return err
		}
		// Drop the directory when nothing else is in it.
		_ = os.Remove(filepath.Dir(filepath.Join(outDir, filepath.FromSlash(rel))))
	}
	return nil
}

func isGenerated(p string) bool {
	data, err := os.ReadFile(p)
	return err == nil && strings.Contains(string(data), generatedMarker)
}

// writeGenerated writes a file krate owns; an existing hand-written one is an error.
func writeGenerated(p string, data []byte, what string) error {
	if _, err := os.Stat(p); err == nil && !isGenerated(p) {
		return fmt.Errorf("%s already exists and was not generated by krate; remove it or merge %s by hand, then re-run `krate deploy`", p, what)
	}
	if err := os.MkdirAll(filepath.Dir(p), 0755); err != nil {
		return err
	}
	return fsutil.WriteFileAtomic(p, data, 0644)
}

// Rule translation to regex routes (Vercel Build Output)

var paramRe = regexp.MustCompile(`:([A-Za-z_][A-Za-z0-9_]*)([*+?]?)`)

// ruleRegex converts a Krate rule source ("/old/*", "/u/:id", "/f/:path*") to
// an anchored regex with named groups and the destination with $name.
func ruleRegex(source, dest string) (string, string) {
	if strings.HasSuffix(source, "/*") {
		base := regexp.QuoteMeta(strings.TrimSuffix(source, "/*"))
		return "^" + base + "(?:/(?<splat>.*))?$", strings.ReplaceAll(dest, ":splat", "$splat")
	}
	var sb strings.Builder
	sb.WriteString("^")
	last := 0
	matches := paramRe.FindAllStringSubmatchIndex(source, -1)
	for _, m := range matches {
		sb.WriteString(regexp.QuoteMeta(source[last:m[0]]))
		name := source[m[2]:m[3]]
		mod := source[m[4]:m[5]]
		switch mod {
		case "*":
			// The leading slash is part of the optional group.
			str := strings.TrimSuffix(sb.String(), "/")
			sb.Reset()
			sb.WriteString(str + "(?:/(?<" + name + ">.*))?")
		case "+":
			sb.WriteString("(?<" + name + ">.+)")
		case "?":
			sb.WriteString("(?<" + name + ">[^/]*)")
		default:
			sb.WriteString("(?<" + name + ">[^/]+)")
		}
		dest = strings.ReplaceAll(dest, ":"+name+mod, "$"+name)
		dest = strings.ReplaceAll(dest, ":"+name, "$"+name)
		last = m[1]
	}
	sb.WriteString(regexp.QuoteMeta(source[last:]))
	sb.WriteString("$")
	return sb.String(), dest
}

func headerSourceRegex(pattern string) string {
	pattern = strings.TrimSpace(pattern)
	if !strings.Contains(pattern, "*") {
		return "^" + regexp.QuoteMeta(pattern) + "$"
	}
	if strings.HasSuffix(pattern, "*") && strings.Count(pattern, "*") == 1 {
		return "^" + regexp.QuoteMeta(strings.TrimSuffix(pattern, "*")) + ".*$"
	}
	return "^" + strings.ReplaceAll(regexp.QuoteMeta(pattern), `\*`, "[^/]*") + "$"
}

// Vercel

type vcRoute map[string]any

func emitVercelServer(cfg *config.Config, root, outDir string, plan *ServerPlan, bundle []byte) ([]string, error) {
	out := filepath.Join(root, ".vercel", "output")
	marker := filepath.Join(out, ".krate-generated")
	if _, err := os.Stat(out); err == nil {
		if _, merr := os.Stat(marker); merr != nil {
			return nil, fmt.Errorf("%s already exists and was not generated by krate; remove it or deploy that output yourself, then re-run `krate deploy --target vercel`", out)
		}
		if err := os.RemoveAll(out); err != nil {
			return nil, err
		}
	}
	staticDir := filepath.Join(out, "static")
	if err := copyTree(outDir, staticDir); err != nil {
		return nil, fmt.Errorf("copying static files: %w", err)
	}
	fnDir := filepath.Join(out, "functions", "__krate.func")
	if err := os.MkdirAll(fnDir, 0755); err != nil {
		return nil, err
	}
	var written []string
	put := func(p string, data []byte) error {
		if err := fsutil.WriteFileAtomic(p, data, 0644); err != nil {
			return err
		}
		written = append(written, p)
		return nil
	}
	if err := put(marker, []byte(generatedMarker+"`\n")); err != nil {
		return nil, err
	}
	if err := put(filepath.Join(fnDir, "index.mjs"), bundle); err != nil {
		return nil, err
	}
	if err := put(filepath.Join(fnDir, "package.json"), []byte("{\"type\":\"module\"}\n")); err != nil {
		return nil, err
	}
	vc, _ := json.MarshalIndent(map[string]any{
		"runtime":                   "nodejs22.x",
		"handler":                   "index.mjs",
		"launcherType":              "Nodejs",
		"shouldAddHelpers":          false,
		"supportsResponseStreaming": true,
	}, "", "  ")
	if err := put(filepath.Join(fnDir, ".vc-config.json"), append(vc, '\n')); err != nil {
		return nil, err
	}

	var routes []vcRoute
	for _, r := range cfg.Headers {
		if r.Source == "" || len(r.Headers) == 0 {
			continue
		}
		routes = append(routes, vcRoute{"src": headerSourceRegex(r.Source), "headers": r.Headers, "continue": true})
	}
	for _, r := range cfg.Redirects {
		src, dst := ruleRegex(r.Source, r.Destination)
		status := 302
		if r.Permanent {
			status = 301
		}
		routes = append(routes, vcRoute{"src": src, "headers": map[string]string{"Location": dst}, "status": status})
	}
	for _, r := range cfg.Rewrites {
		src, dst := ruleRegex(r.Source, r.Destination)
		routes = append(routes, vcRoute{"src": src, "dest": dst, "check": true})
	}
	routes = append(routes, vcRoute{"src": "^/(?:api|__krate)(?:/.*)?$", "dest": "/__krate"})
	for _, g := range plan.ServerPaths {
		if re := globRegex(g); re != "" && g != "/api/*" && g != "/__krate/action/*" {
			routes = append(routes, vcRoute{"src": re, "dest": "/__krate"})
		}
	}
	routes = append(routes, vcRoute{"handle": "filesystem"}, vcRoute{"src": "^/(.*)$", "dest": "/__krate"})
	conf, _ := json.MarshalIndent(map[string]any{"version": 3, "routes": routes}, "", "  ")
	if err := put(filepath.Join(out, "config.json"), append(conf, '\n')); err != nil {
		return nil, err
	}
	sort.Strings(written)
	return written, nil
}

// globRegex turns a URL glob (with "{,/}" or trailing "*") into an anchored regex.
func globRegex(g string) string {
	g = strings.ReplaceAll(g, "{,/}", "\x00")
	q := regexp.QuoteMeta(g)
	q = strings.ReplaceAll(q, `\*`, ".*")
	q = strings.ReplaceAll(q, "\x00", "/?")
	return "^" + q + "$"
}

// Netlify

func emitNetlifyServer(cfg *config.Config, root, outDir string, plan *ServerPlan, bundle []byte) ([]string, error) {
	var written []string
	// The bundle lives outside the functions directory (every file there is a
	// function). The function file is a thin wrapper with a literal `config`
	// export, which is what Netlify's in-source configuration parser reads.
	impl := filepath.Join(root, "netlify", "server", "krate-server.mjs")
	if err := writeGenerated(impl, append([]byte("// "+generatedMarker+" --target netlify`.\n"), bundle...), "the server bundle"); err != nil {
		return nil, err
	}
	written = append(written, impl)
	fn := filepath.Join(root, "netlify", "functions", "krate.mjs")
	wrapper := "// " + generatedMarker + " --target netlify`.\nimport handler from \"../server/krate-server.mjs\";\n\nexport default handler;\nexport const config = { path: \"/*\", preferStatic: true };\n"
	if err := writeGenerated(fn, []byte(wrapper), "the function"); err != nil {
		return nil, err
	}
	written = append(written, fn)
	rel, err := filepath.Rel(root, outDir)
	if err != nil || strings.HasPrefix(rel, "..") {
		rel = "dist"
	}
	toml := "# " + generatedMarker + " --target netlify`.\n[build]\n  publish = \"" + filepath.ToSlash(rel) + "\"\n\n[functions]\n  directory = \"netlify/functions\"\n"
	tomlPath := filepath.Join(root, "netlify.toml")
	if _, err := os.Stat(tomlPath); err == nil && !isGenerated(tomlPath) {
		plan.Warnings = append(plan.Warnings, "netlify.toml exists and was not generated by krate; make sure it sets publish = \""+filepath.ToSlash(rel)+"\" and [functions] directory = \"netlify/functions\"")
	} else {
		if err := writeGenerated(tomlPath, []byte(toml), "the settings"); err != nil {
			return nil, err
		}
		written = append(written, tomlPath)
	}
	files, err := emitRedirects(cfg, outDir)
	if err != nil {
		return nil, err
	}
	hfiles, err := emitHeaders(cfg, outDir)
	if err != nil {
		return nil, err
	}
	written = append(written, files...)
	written = append(written, hfiles...)
	return written, nil
}

// Cloudflare

func emitCloudflareServer(cfg *config.Config, root, outDir string, plan *ServerPlan, bundle []byte) ([]string, error) {
	var written []string
	worker := filepath.Join(root, ".krate", "deploy", "cloudflare", "worker.mjs")
	if err := os.MkdirAll(filepath.Dir(worker), 0755); err != nil {
		return nil, err
	}
	if err := fsutil.WriteFileAtomic(worker, bundle, 0644); err != nil {
		return nil, err
	}
	written = append(written, worker)
	rel, err := filepath.Rel(root, outDir)
	if err != nil || strings.HasPrefix(rel, "..") {
		rel = "dist"
	}
	var first any = true
	if !plan.HasMiddleware {
		var pats []string
		for _, g := range plan.ServerPaths {
			g = strings.ReplaceAll(g, "{,/}", "")
			pats = append(pats, g)
			if !strings.HasSuffix(g, "*") {
				pats = append(pats, g+"/")
			}
		}
		pats = append(pats, "/__krate/*")
		first = dedupe(pats)
	}
	name := sanitizeName(filepath.Base(root))
	conf := map[string]any{
		"name":                name,
		"main":                ".krate/deploy/cloudflare/worker.mjs",
		"compatibility_date":  "2025-09-01",
		"compatibility_flags": []string{"nodejs_compat"},
		"assets": map[string]any{
			"directory":        filepath.ToSlash(rel),
			"binding":          "ASSETS",
			"run_worker_first": first,
		},
	}
	data, _ := json.MarshalIndent(conf, "", "  ")
	text := "// " + generatedMarker + " --target cloudflare`.\n" + string(data) + "\n"
	for _, existing := range []string{"wrangler.jsonc", "wrangler.json", "wrangler.toml"} {
		p := filepath.Join(root, existing)
		if _, err := os.Stat(p); err == nil && !isGenerated(p) {
			plan.Warnings = append(plan.Warnings, existing+" exists and was not generated by krate; make sure it sets main = \".krate/deploy/cloudflare/worker.mjs\", compatibility_flags = [\"nodejs_compat\"] and assets { directory = \""+filepath.ToSlash(rel)+"\", binding = \"ASSETS\", run_worker_first = "+fmt.Sprint(first)+" }")
			return append(written, redirectsAndHeaders(cfg, outDir)...), nil
		}
	}
	p := filepath.Join(root, "wrangler.jsonc")
	if err := writeGenerated(p, []byte(text), "the settings"); err != nil {
		return nil, err
	}
	written = append(written, p)
	return append(written, redirectsAndHeaders(cfg, outDir)...), nil
}

func redirectsAndHeaders(cfg *config.Config, outDir string) []string {
	var out []string
	if f, err := emitRedirects(cfg, outDir); err == nil {
		out = append(out, f...)
	}
	if f, err := emitHeaders(cfg, outDir); err == nil {
		out = append(out, f...)
	}
	return out
}

func dedupe(in []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, s := range in {
		if !seen[s] {
			seen[s] = true
			out = append(out, s)
		}
	}
	return out
}

func sanitizeName(s string) string {
	s = strings.ToLower(s)
	s = regexp.MustCompile(`[^a-z0-9-]+`).ReplaceAllString(s, "-")
	s = strings.Trim(s, "-")
	if s == "" {
		return "krate-app"
	}
	return s
}

func copyTree(src, dst string) error {
	return filepath.Walk(src, func(p string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(src, p)
		if err != nil {
			return err
		}
		target := filepath.Join(dst, rel)
		if info.IsDir() {
			return os.MkdirAll(target, 0755)
		}
		if !info.Mode().IsRegular() {
			return nil
		}
		in, err := os.Open(p)
		if err != nil {
			return err
		}
		defer func() { _ = in.Close() }()
		out, err := os.Create(target)
		if err != nil {
			return err
		}
		if _, err := io.Copy(out, in); err != nil {
			_ = out.Close()
			return err
		}
		return out.Close()
	})
}
